import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
// Keep the downloadable editor usable offline as a single HTML file.
export async function embeddedEditorCore() {
    const source = await readFile(new URL('../shared/band-editor.mjs', import.meta.url), 'utf8');
    return `\n// Generated by sync-editor-core.mjs. Edit ../shared/band-editor.mjs instead.\n(() => {\n${source.replace(/export default BandEditor\s*;?\s*$/, 'globalThis.BandEditor = BandEditor;')}\n})();\n`;
}
export async function syncEditorCore() {
    const target = new URL('./band-json-editor.html', import.meta.url);
    const html = await readFile(target, 'utf8');
    const core = await embeddedEditorCore();
    await writeFile(target, html.replace(/(<script id="editor-core">)[\s\S]*?(<\/script>)/, (_, start, end) => start + core + end));
}
if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1]))
    await syncEditorCore();
